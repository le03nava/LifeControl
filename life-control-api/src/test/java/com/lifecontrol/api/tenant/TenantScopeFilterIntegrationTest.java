package com.lifecontrol.api.tenant;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.jwt;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.lifecontrol.api.common.tenant.TenantScope;
import com.lifecontrol.api.company.model.Company;
import com.lifecontrol.api.support.AbstractPostgresIntegrationTest;
import jakarta.persistence.EntityManager;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.request.RequestPostProcessor;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.servlet.HandlerInterceptor;
import org.springframework.web.servlet.config.annotation.InterceptorRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

/**
 * The scope filter at the HTTP boundary: which requests are refused, which ones proceed, and what the
 * holder carries while a controller runs.
 *
 * <p><b>Why a real chain and a real token.</b> The filter's whole job is to read a validated principal and
 * a URL, so a unit test that constructs it by hand would have to fake exactly the two things under test —
 * authentication and routing. These requests go through {@code SecurityConfig}'s chain with a
 * {@code jwt()} post-processor, so the order ({@code addFilterAfter(..., BearerTokenAuthenticationFilter)})
 * and the refusal path (through {@code ExceptionTranslationFilter}, which is what makes the answer a 403
 * and not a 500) are the production ones.</p>
 *
 * <p><b>How "the holder was set for the duration" is observed.</b> A test interceptor records
 * {@link TenantScope#current()} in {@code preHandle}, which runs after every filter and before the
 * controller: that is a controller's-eye view of the scope, and it is the only honest one — asserting on
 * the holder after the request would only ever prove that it was cleared. The clearing itself is asserted
 * right after, on the same thread, which is also the proof that a thread serving a second request does not
 * inherit the first one's tenant.</p>
 *
 * <p>PostgreSQL, not H2, for the same reason every suite in this package is: the scope's effect is a
 * policy, and a policy does not exist on H2 — but the filter itself needs a working application context
 * with Flyway's schema, which is what the base class supplies.</p>
 */
@SpringBootTest
@AutoConfigureMockMvc
@Transactional
@DisplayName("Tenant scope filter — HTTP acceptance")
class TenantScopeFilterIntegrationTest extends AbstractPostgresIntegrationTest {

    private static final String SUBJECT = "kc-subject-filter";

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private EntityManager entityManager;

    /** The company the token claims, generated by the entity and not by this suite. */
    private UUID claimedCompany;

    /** A company of the same database the token does not claim. */
    private UUID foreignCompany;

    /**
     * Records the holder a controller would see. Static because the interceptor is registered by a
     * {@code @TestConfiguration}, which is not the test instance.
     */
    @TestConfiguration
    static class ScopeRecorderConfiguration implements WebMvcConfigurer {

        static final AtomicReference<TenantScope.Scope> SEEN = new AtomicReference<>();

        @Override
        public void addInterceptors(InterceptorRegistry registry) {
            registry.addInterceptor(new HandlerInterceptor() {
                @Override
                public boolean preHandle(HttpServletRequest request, HttpServletResponse response, Object handler) {
                    SEEN.set(TenantScope.current().orElse(null));
                    return true;
                }
            });
        }
    }

    @BeforeEach
    void seedTheTwoCompaniesAndForgetTheLastRequest() {
        ScopeRecorderConfiguration.SEEN.set(null);
        TenantScope.clear();
        // The ids come from the entity's own generator: `companies.id` is a generated UUID, so building a
        // Company with an assigned id makes Hibernate read the instance as detached and refuse to persist
        // it.
        claimedCompany = persistCompany("TENANT-SCOPE-CLAIMED", "TSCO010101AB");
        foreignCompany = persistCompany("TENANT-SCOPE-FOREIGN", "TSFO010101AB");
    }

    @Test
    @DisplayName("a path naming a company outside the token's claims is refused")
    void aCompanyOutsideTheClaimsIsRefused() throws Exception {
        mockMvc.perform(get("/api/companies/{id}", foreignCompany).with(token(claimedCompany)))
                .andExpect(status().isForbidden());

        assertThat(ScopeRecorderConfiguration.SEEN.get())
                .as("the refusal happens before any controller runs, so no scope was ever handed to one")
                .isNull();
        assertThat(TenantScope.current())
                .as("a refused request leaves no scope behind on the thread that served it")
                .isEmpty();
    }

    @Test
    @DisplayName("a path naming a company inside the claims proceeds with the scope stated")
    void aClaimedCompanyProceedsWithTheScopeStated() throws Exception {
        mockMvc.perform(get("/api/companies/{id}", claimedCompany).with(token(claimedCompany)))
                .andExpect(status().isOk());

        assertThat(ScopeRecorderConfiguration.SEEN.get())
                .as("the controller sees the company the path named and the caller's own subject")
                .isEqualTo(new TenantScope.Scope(claimedCompany, SUBJECT));
        assertThat(TenantScope.current())
                .as("and the filter cleared it in a finally, so the next request on this thread starts empty")
                .isEmpty();
    }

    @Test
    @DisplayName("a path with no company segment states the subject alone")
    void aPathWithoutACompanySegmentStatesOnlyTheSubject() throws Exception {
        // `selector` is a literal segment of `/api/companies/...`, not a company id: the filter must not
        // read it as a tenant, and a tenant read with a garbage scope is exactly what would break this
        // endpoint once policies are armed.
        mockMvc.perform(get("/api/companies/selector").with(token(claimedCompany)))
                .andExpect(status().isOk());

        assertThat(ScopeRecorderConfiguration.SEEN.get())
                .as("the subject alone: user_preferences is read before a company is known, and inventing "
                        + "one from a multi-valued claim is the widening this slice refuses")
                .isEqualTo(new TenantScope.Scope(null, SUBJECT));
    }

    @Test
    @DisplayName("two requests on the same thread do not share a scope")
    void aSecondRequestOnTheSameThreadStartsWithoutAScope() throws Exception {
        mockMvc.perform(get("/api/companies/{id}", claimedCompany).with(token(claimedCompany)))
                .andExpect(status().isOk());
        assertThat(TenantScope.current())
                .as("MockMvc runs both requests on this one thread, which is the pooled thread of a real "
                        + "server: the first scope must not survive into the second request")
                .isEmpty();

        mockMvc.perform(get("/api/companies/selector").with(token(claimedCompany)))
                .andExpect(status().isOk());

        assertThat(ScopeRecorderConfiguration.SEEN.get())
                .as("the second request saw its own scope — subject only — and not the first one's company")
                .isEqualTo(new TenantScope.Scope(null, SUBJECT));
    }

    @Test
    @DisplayName("an administrator is admitted to any company, and the scope is still that company")
    void anAdministratorIsAdmittedToAnyCompany() throws Exception {
        // `verifyCompanyAccess` admits an administrator without a per-company claim, and this filter
        // delegates to it on purpose: a second membership rule here would refuse every administrator
        // request that names a company its token does not list, which is most of them.
        mockMvc.perform(get("/api/companies/{id}", foreignCompany).with(administratorToken()))
                .andExpect(status().isOk());

        assertThat(ScopeRecorderConfiguration.SEEN.get())
                .as("admitted, and scoped to the company the path names — never to a wider one")
                .isEqualTo(new TenantScope.Scope(foreignCompany, SUBJECT));
        assertThat(TenantScope.current()).isEmpty();
    }

    // ──────────────────────────────────────
    // helpers
    // ──────────────────────────────────────

    private static RequestPostProcessor token(UUID claimedCompany) {
        return jwt().authorities(new SimpleGrantedAuthority("ROLE_lc-company"))
                .jwt(builder -> builder.subject(SUBJECT).claim("company_id", claimedCompany.toString()));
    }

    private static RequestPostProcessor administratorToken() {
        return jwt().authorities(new SimpleGrantedAuthority("ROLE_lc-admin")).jwt(builder -> builder.subject(SUBJECT));
    }

    private UUID persistCompany(String companyKey, String rfc) {
        var company = Company.builder()
                .companyKey(companyKey)
                .companyName("Tenant Scope " + companyKey)
                .rfc(rfc)
                .enabled(true)
                .build();
        entityManager.persist(company);
        entityManager.flush();
        return company.getId();
    }
}
